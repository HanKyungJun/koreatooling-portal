let _lastChanged = 'vc';
function doCalcVc()  { _lastChanged = 'vc';  doCalc(); }
function doCalcRpm() { _lastChanged = 'rpm'; doCalc(); }
function doCalc() {
  const D   = parseFloat(document.getElementById('cD').value);
  const Vc  = parseFloat(document.getElementById('cVc').value);
  const Rpm = parseFloat(document.getElementById('cRpm').value);
  const out = document.getElementById('calcOut');
  if (!D || D <= 0) { out.textContent = 'D를 먼저 입력'; return; }
  if (_lastChanged === 'vc' && Vc > 0) {
    const n = Math.round(Vc * 1000 / (Math.PI * D));
    document.getElementById('cRpm').value = n;
    out.textContent = `N = ${n.toLocaleString()} rpm`;
  } else if (_lastChanged === 'rpm' && Rpm > 0) {
    const vc = (Rpm * Math.PI * D / 1000).toFixed(1);
    document.getElementById('cVc').value = vc;
    out.textContent = `Vc = ${vc} m/min`;
  }
}

