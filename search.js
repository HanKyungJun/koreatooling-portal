const MAT_MAP = {
  '탄소강': ['탄소강','SS','SC','FC','HP','SM','S45C','S50C','일반구조강','저탄소강'],
  'SUS':    ['SUS','SUS304','SUS316','스테인리스'],
  '알루미늄':['알루미늄','AL','알루','A7075','AL7075','AC4B','비철','동합금'],
  '경화강': ['경화강','NAK','SKD','STAVAX','SKH','YXR','HRc','HPM','경화'],
  'Ti':     ['Ti','Ti6Al4V','티타늄','내열합금'],
};

function matchesMat(item) {
  if (filters.mat === 'all') return true;
  const terms = MAT_MAP[filters.mat] || [];
  return terms.some(t => item.keywords.some(k => k.toLowerCase().includes(t.toLowerCase())));
}

function renderResults() {
  const q = document.getElementById('searchInput').value.trim().toLowerCase();
  const tokens = q.split(/\s+/).filter(Boolean);

  let list = CATALOG.filter(item => {
    if (filters.mfg !== 'all' && item.mfg !== filters.mfg) return false;
    if (filters.type !== 'all' && item.type !== filters.type) return false;
    if (!matchesMat(item)) return false;
    if (tokens.length === 0) return true;
    const hay = [item.title, item.subtitle, item.series, ...item.keywords].join(' ').toLowerCase();
    return tokens.every(t => hay.includes(t));
  });

  document.getElementById('resultCount').textContent = `결과 ${list.length}건 / 전체 ${CATALOG.length}건`;

  const out = document.getElementById('results');
  if (list.length === 0) {
    out.innerHTML = '<div class="empty">검색 결과가 없습니다.<br><small>피삭재·시리즈명·날경으로 다시 검색해 보세요.</small></div>';
    return;
  }

  out.innerHTML = list.map(item => renderCard(item)).join('');
}

function makeRequestUrl(item) {
  const typeMap = { '평엔드밀': '평엔드밀', '볼엔드밀': '볼엔드밀', '코너엔드밀': '코너엔드밀', '드릴': '드릴' };
  const t = encodeURIComponent(typeMap[item.type] || item.type);
  const s = encodeURIComponent(item.series);
  const m = encodeURIComponent(item.mfg);
  return `request.html?tool_type=${t}&series=${s}&mfg=${m}`;
}

function renderCard(item) {
  const typeBadge = item.type === '드릴' ? 'badge-drill'
                  : item.type === '볼엔드밀' ? 'badge-ball'
                  : item.type === '코너엔드밀' ? 'badge-corner' : 'badge-em';
  const mfgBadge  = item.mfg === 'JJ' ? 'badge-jj' : 'badge-cogo';

  let html = `<div class="card">
    <div class="card-header">
      <span class="badge ${mfgBadge}">${item.mfg}</span>
      <span class="badge ${typeBadge}">${item.type}</span>
      <span class="card-title">${item.title}</span>
      <span class="card-subtitle" style="flex:1;">${item.subtitle}</span>
      <a class="request-btn" href="${makeRequestUrl(item)}" title="이 시리즈로 재연마 의뢰 접수">🔧 재연마 의뢰</a>
    </div>`;

  if (item.warn) html += `<div class="warn">⚠️ ${item.warn}</div>`;
  if (item.note) html += `<div class="note">📝 ${item.note.replace(/\n/g,'<br>')}</div>`;
  if (item.calc_note) html += `<div class="calc-box">📐 ${item.calc_note}</div>`;

  item.tables.forEach(tbl => {
    html += `<div style="padding:4px 14px 2px;font-size:12px;color:#555;font-weight:600;">${tbl.label}</div>`;
    html += `<div style="overflow-x:auto;padding:0 0 8px;"><table>
      <thead><tr>${tbl.cols.map(c=>`<th>${c}</th>`).join('')}</tr></thead>
      <tbody>${tbl.rows.map((r) => `<tr>${r.map((cell,ci) => {
        const cls = ci===0 ? 'td-left td-highlight' : '';
        return `<td class="${cls}">${cell}</td>`;
      }).join('')}</tr>`).join('')}</tbody>
    </table></div>`;
  });

  html += `</div>`;
  return html;
}

